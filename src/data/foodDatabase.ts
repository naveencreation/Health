/**
 * Intelligent helper to supply appetizing, informative descriptions for any food item.
 */
export function getFoodDescription(item?: Partial<FoodItem> | null): string {
  if (!item) return 'A delicious, nutrient-packed dish crafted for balanced daily nutrition.';
  if (item.description && item.description.trim().length > 0) {
    return item.description;
  }
  const name = (item.name || '').toLowerCase();
  
  if (name.includes('idli')) {
    return 'Freshly fermented and steamed until soft and fluffy. Rich in gut-friendly probiotics, easily digestible carbs, and low in fat for clean morning energy.';
  }
  if (name.includes('dosa')) {
    return 'Crisp, golden crepe made from traditionally fermented rice and black lentils. Wholesome complex carbohydrates paired with gentle digestion.';
  }
  if (name.includes('paratha')) {
    return 'Hearty whole-wheat flatbread griddled to golden perfection. Grounding comfort food that supplies sustained complex energy throughout the day.';
  }
  if (name.includes('roti') || name.includes('chapati')) {
    return 'Traditional unleavened flatbread crafted from 100% stoneground whole wheat. High in dietary fiber to support steady blood sugar balance.';
  }
  if (name.includes('biryani')) {
    return 'Fragrant long-grain basmati rice layered with aromatic spices and wholesome protein. Balanced macronutrients providing sustained satiety.';
  }
  if (name.includes('paneer')) {
    return 'Fresh cottage cheese cubes delivering slow-digesting casein protein and bioavailable calcium to nourish and preserve lean muscle tissue.';
  }
  if (name.includes('chicken')) {
    return 'Lean, high-yield biological protein essential for muscle synthesis, cellular repair, and metabolic efficiency.';
  }
  if (name.includes('apple')) {
    return 'Crisp orchard fruit rich in soluble pectin fiber, vitamin C, and polyphenols to encourage healthy digestion and daily vitality.';
  }
  if (name.includes('banana')) {
    return 'Natural energy fruit loaded with potassium, vitamin B6, and fast-absorbing simple carbs to fuel active workouts and reduce fatigue.';
  }
  if (name.includes('rice') || name.includes('khichdi') || name.includes('pulao')) {
    return 'Easily digestible grain base that provides quick-burning cellular fuel, perfect for fueling active afternoons or post-workout recovery.';
  }
  if (name.includes('poha')) {
    return 'Light flattened rice tempered with mustard seeds, turmeric, and peanuts for a quick, iron-rich morning fuel.';
  }

  // Generic fallback based on dominant macro
  const protein = item.protein || 0;
  const carbs = item.carbs || 0;
  if (protein >= 10) {
    return `High-protein nutritional choice delivering ${protein}g of protein per serving, designed to maintain muscle health and promote lasting satiety.`;
  }
  if (carbs >= 20) {
    return `Clean, energizing carbohydrate source providing ${carbs}g of carbs to fuel your daily physical activity and mental focus.`;
  }
  return 'A wholesome, nutrient-dense choice that fits seamlessly into your daily caloric and macronutrient targets.';
}
