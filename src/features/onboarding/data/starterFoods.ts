export function getStarterFoods(foodStyle?: FoodStyle): StarterFoodItem[] {
  if (foodStyle && STARTER_FOODS_BY_STYLE[foodStyle]) {
    return STARTER_FOODS_BY_STYLE[foodStyle];
  }
  return STARTER_FOODS_BY_STYLE.default;
}

export function guessMealSlotFromTime(now = new Date()): 'breakfast' | 'lunch' | 'dinner' | 'snack' {
  const hour = now.getHours();
  if (hour >= 5 && hour < 11) return 'breakfast';
  if (hour >= 11 && hour < 16) return 'lunch';
  if (hour >= 16 && hour < 19) return 'snack';
  return 'dinner';
}
